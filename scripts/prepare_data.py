#!/usr/bin/env python3
"""Rebuild the documented 2011 sample and offline browser data from UCI.

Run from any directory: python scripts/prepare_data.py --archive /path/to/archive.zip
Omit --archive to download the official pinned archive (network required once).
Uses only Python's standard library. Student notebooks use the bundled CSV.
"""

import argparse
import csv
import hashlib
import io
import json
from pathlib import Path
from urllib.request import urlopen
from zipfile import ZipFile

ROOT = Path(__file__).resolve().parents[1]
URL = "https://archive.ics.uci.edu/static/public/275/bike+sharing+dataset.zip"
# Pinned to the official archive retrieved and verified on 2026-10-12.
ARCHIVE_SHA256 = "b70182d0d0508e9abbb79306ce5c0cec34869000f8220175ac83d11dbe845401"


def sha256(value):
    return hashlib.sha256(value).hexdigest()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--archive", type=Path, help="Previously downloaded official ZIP")
    parser.add_argument("--retrieved-on", default="2026-10-12",
                        help="Date the supplied archive was retrieved (YYYY-MM-DD)")
    args = parser.parse_args()
    if args.archive:
        archive = args.archive.read_bytes()
    else:
        with urlopen(URL, timeout=60) as response:
            archive = response.read()
    if sha256(archive) != ARCHIVE_SHA256:
        raise ValueError("Archive checksum changed. Audit the source before updating the pin.")
    with ZipFile(io.BytesIO(archive)) as bundle:
        original = bundle.read("day.csv")
        source_readme = bundle.read("Readme.txt")
    source_rows = list(csv.DictReader(io.StringIO(original.decode("utf-8-sig"))))
    columns = ["dteday", "cnt", "workingday", "mnth"]
    rows = [{key: row[key] for key in columns} for row in source_rows
            if "2011-01-01" <= row["dteday"] <= "2011-12-31"]
    rows.sort(key=lambda row: row["dteday"])
    assert len(source_rows) == 731 and len(rows) == 365
    assert len({row["dteday"] for row in rows}) == 365
    output = io.StringIO(newline="")
    writer = csv.DictWriter(output, fieldnames=columns, lineterminator="\n")
    writer.writeheader()
    writer.writerows(rows)
    csv_bytes = output.getvalue().encode("utf-8")
    data = ROOT / "data"
    data.mkdir(exist_ok=True)
    (data / "bike_daily_2011.csv").write_bytes(csv_bytes)
    browser_rows = [{"dteday": row["dteday"], "cnt": int(row["cnt"]),
                     "workingday": int(row["workingday"])} for row in rows]
    js = ("// Observed UCI Bike Sharing data; see PROVENANCE.md for CC BY 4.0 attribution.\n"
          "// Generated by scripts/prepare_data.py; counts are completed rentals/day.\n"
          "window.COURSE_BIKE_DATA = " + json.dumps(browser_rows, separators=(",", ":")) + ";\n")
    (data / "bike_daily_2011.js").write_text(js, encoding="utf-8")
    (data / "source_readme.txt").write_bytes(source_readme)
    metadata = {
        "dataset": "Bike Sharing", "creator": "Hadi Fanaee-T", "year": 2013,
        "doi": "10.24432/C5W894",
        "source_page": "https://archive.ics.uci.edu/dataset/275/bike+sharing+dataset",
        "archive_url": URL, "retrieved_on": args.retrieved_on,
        "license": "CC BY 4.0", "license_url": "https://creativecommons.org/licenses/by/4.0/",
        "license_verified_on": "2026-10-12",
        "license_evidence": "UCI dataset landing page, License section",
        "archive_sha256": sha256(archive), "source_member": "day.csv",
        "source_member_sha256": sha256(original), "source_rows": len(source_rows),
        "sample_sha256": sha256(csv_bytes), "browser_js_sha256": sha256(js.encode("utf-8")),
        "sample_rows": len(rows), "date_start": rows[0]["dteday"],
        "date_end": rows[-1]["dteday"], "sample_columns": columns,
        "derivation": "Filter day.csv to 2011-01-01 through 2011-12-31 inclusive; retain dteday,cnt,workingday,mnth; sort ascending date; UTF-8 CSV with LF endings. No imputation, rescaling, or synthetic records.",
        "units": {"cnt": "completed rentals per calendar day (not unique bicycles or latent demand)",
                  "dteday": "source calendar date", "workingday": "1 if neither weekend nor holiday; 0 otherwise",
                  "mnth": "month number, 1 through 12"},
        "scenario_assumptions": {"threshold_rentals_per_day": 4000,
                                 "threshold_is_measured_capacity": False},
        "chronological_split": {"train": "2011-01-01 to 2011-08-31, 243 days",
                                "test": "2011-09-01 to 2011-12-31, 122 days"},
    }
    (data / "source_metadata.json").write_text(json.dumps(metadata, indent=2) + "\n", encoding="utf-8")
    print(f"Wrote {len(rows)} observed daily records to {data}")
    print(f"CSV SHA-256: {sha256(csv_bytes)}")


if __name__ == "__main__":
    main()
